// Finds a YouTube video for every track of every element and verifies that it can be embedded.
//
//   node tools/find-tracks.mjs            # fill in missing ids only
//   node tools/find-tracks.mjs --all      # re-search every track
//   node tools/find-tracks.mjs 1 43 104   # re-search all tracks of specific atomic numbers
//
// For each track it takes the top YouTube search results, then checks each candidate
// through YouTube's oEmbed endpoint. oEmbed returns 401/403 when a video can't be embedded,
// so the first candidate that passes is kept. Results are written to data/tracks.js
// after every match, so an interrupted run keeps what it found.
// Each match is printed with its video title so you can eyeball it for mismatches; a "?" marks
// a video whose title shares no word with the track title, which is worth checking by hand.
// Ids are keyed by "Artist — Title", and ids for tracks no element uses any more are dropped.

import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ctx = {};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, 'data/elements.js'), 'utf8') + ';this.ELEMENTS=ELEMENTS', ctx);
const elements = ctx.ELEMENTS;

const tracksFile = path.join(root, 'data/tracks.js');
let existing = {};
if (fs.existsSync(tracksFile)) {
  const c = {};
  vm.createContext(c);
  vm.runInContext(fs.readFileSync(tracksFile, 'utf8') + ';this.TRACKS=TRACKS', c);
  existing = c.TRACKS;
}

const args = process.argv.slice(2);
const all = args.includes('--all');
const only = args.filter((a) => /^\d+$/.test(a)).map(Number);

const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126 Safari/537.36';
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// Retries dropped connections with backoff, so one network blip doesn't skip a track.
async function get(url, opts) {
  for (let attempt = 1; ; attempt++) {
    try {
      return await fetch(url, opts);
    } catch (e) {
      if (attempt >= 4) throw e;
      await sleep(1500 * attempt);
    }
  }
}

async function search(q) {
  const url = 'https://www.youtube.com/results?hl=en&search_query=' + encodeURIComponent(q);
  const html = await (await get(url, { headers: { 'User-Agent': UA, 'Accept-Language': 'en' } })).text();
  const ids = [...html.matchAll(/"videoRenderer":\{"videoId":"([\w-]{11})"/g)].map((m) => m[1]);
  return [...new Set(ids)].slice(0, 5);
}

async function oembed(id) {
  const res = await get('https://www.youtube.com/oembed?format=json&url=' +
    encodeURIComponent('https://www.youtube.com/watch?v=' + id));
  if (!res.ok) return null;
  return res.json();
}

const used = new Set(elements.flatMap((el) => el.tracks.map((t) => t.key)));
const out = Object.fromEntries(Object.entries(existing).filter(([k]) => used.has(k)));
const quote = (s) => "'" + s.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";

function save() {
  const lines = Object.keys(out).sort((a, b) => a.localeCompare(b, 'en', { sensitivity: 'base' }))
    .map((k) => `  ${quote(k)}: '${out[k]}',`);
  fs.writeFileSync(tracksFile,
    '// YouTube video ids keyed by "Artist — Title" (as written in data/elements.js).\n' +
    '// Generated by tools/find-tracks.mjs; safe to hand-edit.\n' +
    'const TRACKS = {\n' + lines.join('\n') + '\n};\n');
}

const words = (s) => s.toLowerCase().normalize('NFKD').replace(/[^a-z0-9 ]+/g, ' ').split(' ').filter((w) => w.length > 2);
const done = new Set();

for (const el of elements) for (const track of el.tracks) {
  const todo = only.length ? only.includes(el.n) : all || !out[track.key];
  if (!todo || done.has(track.key)) continue;
  done.add(track.key);
  const q = `${track.artist} ${track.title}`;
  let picked = null;
  try {
    for (const id of await search(q)) {
      const meta = await oembed(id);
      if (meta) { picked = { id, title: meta.title, channel: meta.author_name }; break; }
    }
  } catch (e) {
    console.log(`${el.n}\t${el.name}\tERROR ${e.message}`);
    continue;
  }
  if (picked) {
    out[track.key] = picked.id;
    save();
    const hit = words(track.title).some((w) => words(picked.title).includes(w));
    console.log(`${el.n}\t${q}\t=> ${picked.id}\t${hit ? '' : '? '}${picked.title}\t[${picked.channel}]`);
  } else {
    console.log(`${el.n}\t${q}\t=> NOT FOUND`);
  }
  await sleep(250);
}

save();
console.log(`\n${Object.keys(out).length}/${used.size} tracks have ids.`);
